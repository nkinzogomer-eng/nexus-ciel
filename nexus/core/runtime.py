from __future__ import annotations

import time

from nexus.bus import AsyncEventBus
from nexus.schemas import Event, Mission, Report

from .capability_registry import CapabilityRegistry
from .mission_journal import MissionJournal
from .state_graph import StateGraph
from .verification import DeterministicOutputVerifier


class NexusRuntime:
    """Mission runtime with explicit separation between generation and proof.

    A provider response is an execution artifact, not evidence of success.
    PASS requires a deterministic acceptance oracle attached to the mission.
    """

    def __init__(self, router: object | None = None, verifier: object | None = None) -> None:
        self.bus = AsyncEventBus()
        self.state_graph = StateGraph()
        self.journal = MissionJournal()
        self.registry = CapabilityRegistry()
        self.reports: dict[str, Report] = {}
        self.router = router
        self.verifier = verifier or DeterministicOutputVerifier()

    async def accept(self, mission: Mission) -> str:
        started = time.perf_counter()
        self.state_graph.create(mission)
        self.journal.append(mission.mission_id, "mission_accepted", "manas", mission.model_dump(mode="json"))
        await self.bus.publish(
            Event(type="MissionAccepted", mission_id=mission.mission_id, payload={"objective": mission.objective})
        )
        self.state_graph.update(mission.mission_id, status="in_progress", iterations=1)

        if self.router is None:
            report = Report(
                mission_id=mission.mission_id,
                verdict="PARTIAL",
                objective=mission.objective,
                summary="mission accepted but no execution provider or independent result is configured",
                iterations=1,
                validation={
                    "criteria": [{"name": "execution provider configured", "passed": False}],
                    "verification": {"verdict": "PARTIAL", "reason": "no execution result"},
                },
                duration_s=round(time.perf_counter() - started, 6),
            )
        else:
            report = await self._execute_routed(mission, started)

        self.reports[str(mission.mission_id)] = report
        status = {"PASS": "validated", "PARTIAL": "partial", "FAIL": "abandoned"}[report.verdict]
        self.state_graph.update(mission.mission_id, status=status)
        self.journal.append(
            mission.mission_id,
            "mission_completed",
            "mission_runtime",
            {"verdict": report.verdict, "state": status, "report": report.model_dump(mode="json")},
        )
        await self.bus.publish(
            Event(type="MissionCompleted", mission_id=mission.mission_id, payload={"verdict": report.verdict})
        )
        return str(mission.mission_id)

    async def _execute_routed(self, mission: Mission, started: float) -> Report:
        from nexus.providers import CompletionRequest
        from nexus.router import RoutingExhausted

        request = CompletionRequest(
            prompt=mission.objective,
            mission_id=str(mission.mission_id),
            critical=mission.priority == "urgent",
        )
        before = len(self.router.decisions)
        try:
            result = await self.router.complete(request)
        except RoutingExhausted as exc:
            trace = self.router.trace()[before:]
            self.journal.append(
                mission.mission_id, "routing_exhausted", "router", {"detail": str(exc), "trace": trace}
            )
            return Report(
                mission_id=mission.mission_id,
                verdict="FAIL",
                objective=mission.objective,
                summary=str(exc),
                iterations=max(len(trace), 1),
                cost_usd=round(sum(step["cost_usd"] for step in trace), 10),
                duration_s=round(time.perf_counter() - started, 6),
                actions=trace,
                validation={"criteria": [{"name": "provider returned sufficient result", "passed": False}]},
            )

        trace = self.router.trace()[before:]
        chosen = trace[-1] if trace else {"stage": "unknown", "provider": "unknown"}
        self.journal.append(
            mission.mission_id,
            "routing_decided",
            "router",
            {"stage": chosen["stage"], "provider": chosen["provider"], "trace": trace},
        )

        verification = self.verifier.verify(mission, result.text)
        self.journal.append(
            mission.mission_id,
            "mission_verification",
            "verification_engine",
            {
                "verdict": verification.verdict,
                "criteria": verification.criteria,
                "evidence": verification.evidence,
            },
        )
        summary = (
            f"output generated by {chosen['provider']} at stage {chosen['stage']}; "
            f"deterministic verification: {verification.verdict}"
        )
        return Report(
            mission_id=mission.mission_id,
            verdict=verification.verdict,
            objective=mission.objective,
            summary=summary,
            iterations=max(len(trace), 1),
            output=result.text,
            cost_usd=round(sum(step["cost_usd"] for step in trace), 10),
            duration_s=round(time.perf_counter() - started, 6),
            actions=trace,
            validation={
                "criteria": verification.criteria,
                "verification": verification.evidence,
                "confidence": result.confidence,
                "confidence_is_not_proof": True,
            },
        )

    def report(self, mission_id: str) -> Report | None:
        return self.reports.get(mission_id)
